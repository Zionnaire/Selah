// Turns the web app's design tokens into the native theme, so the two cannot drift apart.
// Reads packages/tokens/src/tokens.css and writes src/theme/tokens.generated.ts. Run by npm start.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(join(here, '..', '..', 'packages', 'tokens', 'src', 'tokens.css'), 'utf8');

/** The `--name: value;` pairs inside the first block that starts with the given selector. */
function block(selector) {
  const start = css.indexOf(selector);
  if (start < 0) throw new Error(`tokens.css has no ${selector} block`);
  const open = css.indexOf('{', start);
  const close = css.indexOf('\n}', open);
  const body = css.slice(open + 1, close);
  const out = {};
  for (const m of body.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)) out[m[1]] = m[2].trim();
  return out;
}

const camel = (k) => k.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const isColour = (v) => /^#[0-9a-f]{3,8}$/i.test(v) || /^rgba?\(/i.test(v);

const root = block(':root {');
const dark = block(":root[data-theme='dark']");

const colours = (o) => Object.fromEntries(Object.entries(o).filter(([, v]) => isColour(v)).map(([k, v]) => [camel(k), v]));
const px = (v) => (v.endsWith('rem') ? Math.round(parseFloat(v) * 16 * 100) / 100 : parseFloat(v));
const scale = (prefix) =>
  Object.fromEntries(Object.entries(root).filter(([k, v]) => k.startsWith(`${prefix}-`) && /^[\d.]+(rem|px)$/.test(v)).map(([k, v]) => [camel(k.slice(prefix.length + 1)), px(v)]));

const light = colours(root);
const darkTheme = { ...light, ...colours(dark) };

const file = `// Generated by scripts/tokens.mjs from packages/tokens/src/tokens.css. Do not edit by hand.
export const light = ${JSON.stringify(light, null, 2)} as const;

export const dark = ${JSON.stringify(darkTheme, null, 2)} as const;

export const fontSize = ${JSON.stringify(scale('text'), null, 2)} as const;

export const radius = ${JSON.stringify(scale('r'), null, 2)} as const;

export const space = ${JSON.stringify(scale('space'), null, 2)} as const;
`;

mkdirSync(join(here, '..', 'src', 'theme'), { recursive: true });
writeFileSync(join(here, '..', 'src', 'theme', 'tokens.generated.ts'), file);
console.log('theme written:', Object.keys(light).length, 'light colours,', Object.keys(darkTheme).length, 'dark colours');
